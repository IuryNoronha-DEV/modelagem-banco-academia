-- Sprint 5 | Sistema de Academia | PostgreSQL
-- Banco organizado em schema próprio para não sobrescrever as tabelas das semanas anteriores.
CREATE SCHEMA IF NOT EXISTS academia_sprint5;
SET search_path TO academia_sprint5, public;

CREATE TABLE IF NOT EXISTS aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf CHAR(11) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    data_nascimento DATE NOT NULL CHECK (data_nascimento < CURRENT_DATE),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS professor (
    id_professor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf CHAR(11) NOT NULL UNIQUE,
    email VARCHAR(160) NOT NULL UNIQUE,
    especialidade VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    contratado_em DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS plano (
    id_plano BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    duracao_meses SMALLINT NOT NULL CHECK (duracao_meses BETWEEN 1 AND 36),
    permite_aulas_coletivas BOOLEAN NOT NULL DEFAULT TRUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS modalidade (
    id_modalidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao TEXT,
    capacidade SMALLINT NOT NULL DEFAULT 20 CHECK (capacidade BETWEEN 1 AND 100),
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS unidade (
    id_unidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    endereco TEXT NOT NULL,
    cidade VARCHAR(80) NOT NULL DEFAULT 'São Luís',
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS matricula (
    id_matricula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT NOT NULL REFERENCES aluno(id_aluno),
    id_plano BIGINT NOT NULL REFERENCES plano(id_plano),
    data_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    data_fim DATE,
    status VARCHAR(15) NOT NULL DEFAULT 'ATIVA' CHECK (status IN ('ATIVA','CANCELADA','ENCERRADA')),
    CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE TABLE IF NOT EXISTS aula (
    id_aula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    id_professor BIGINT NOT NULL REFERENCES professor(id_professor),
    id_modalidade BIGINT NOT NULL REFERENCES modalidade(id_modalidade),
    id_unidade BIGINT NOT NULL REFERENCES unidade(id_unidade),
    inicio TIMESTAMPTZ NOT NULL,
    duracao_minutos SMALLINT NOT NULL DEFAULT 60 CHECK (duracao_minutos BETWEEN 15 AND 240),
    vagas SMALLINT NOT NULL DEFAULT 15 CHECK (vagas BETWEEN 1 AND 100),
    status VARCHAR(15) NOT NULL DEFAULT 'AGENDADA' CHECK (status IN ('AGENDADA','REALIZADA','CANCELADA'))
);

CREATE TABLE IF NOT EXISTS participacao_aula (
    id_participacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aula BIGINT NOT NULL REFERENCES aula(id_aula) ON DELETE CASCADE,
    id_aluno BIGINT NOT NULL REFERENCES aluno(id_aluno),
    inscrito_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    presenca BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (id_aula, id_aluno)
);

CREATE TABLE IF NOT EXISTS pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_matricula BIGINT NOT NULL REFERENCES matricula(id_matricula),
    valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
    vencimento DATE NOT NULL,
    pago_em TIMESTAMPTZ,
    metodo VARCHAR(15) NOT NULL CHECK (metodo IN ('PIX','CREDITO','DEBITO','DINHEIRO','BOLETO')),
    status VARCHAR(15) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','PAGO','ATRASADO','CANCELADO')),
    referencia VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS equipamento (
    id_equipamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    numero_patrimonio VARCHAR(30) NOT NULL UNIQUE,
    id_modalidade BIGINT REFERENCES modalidade(id_modalidade),
    data_aquisicao DATE NOT NULL DEFAULT CURRENT_DATE,
    valor_aquisicao NUMERIC(12,2) NOT NULL CHECK (valor_aquisicao >= 0),
    em_uso BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes TEXT
);

CREATE TABLE IF NOT EXISTS avaliacao (
    id_avaliacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno BIGINT NOT NULL REFERENCES aluno(id_aluno),
    id_professor BIGINT NOT NULL REFERENCES professor(id_professor),
    realizada_em DATE NOT NULL DEFAULT CURRENT_DATE,
    peso_kg NUMERIC(5,2) CHECK (peso_kg BETWEEN 20 AND 400),
    altura_m NUMERIC(3,2) CHECK (altura_m BETWEEN 0.80 AND 2.50),
    nota SMALLINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    observacao TEXT
);

-- Total: 11 tabelas relacionadas por PKs e FKs.
